  // ── APPLY PATCH ──────────────────────────────────────────
  function applyPatch() {
    if (!window.ALL_PLACES) return;

    let patched = 0;
    window.ALL_PLACES.forEach(place => {
      if (IMAGE_MAP_PART2[place.id]) {
        place.image = IMAGE_MAP_PART2[place.id];
        patched++;
      } else if (
        place.image &&
        (place.image.includes('picsum.photos') || place.image.includes('random='))
      ) {
        place.image = FALLBACK[place.category] || FALLBACK['default'];
        patched++;
      }
    });

    console.log(`[Yatra Image Patch Part 2] ✅ Patched ${patched} additional place images.`);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyPatch);
  } else {
    applyPatch();
  }

